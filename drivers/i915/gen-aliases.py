"""Generate opt-in alias data from the pinned Linux PCI IDs, not gfx-drm.

Usage: gen-aliases.py <patched Linux tree> > packaging/i915n.aliases
The groups match patch 0009's PCH Gen6-Gen9.5 admission boundary. They must
be reviewed together when that boundary changes. Requires a C preprocessor.
"""
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys

header = Path(sys.argv[1]).resolve() / "include/drm/intel/pciids.h"
groups = ("SNB", "IVB", "HSW", "BDW", "SKL", "KBL", "CFL", "CML")
source = '#include "' + str(header) + '"\n#define ALIAS(id, ...) id\n'
source += "\n".join(f"INTEL_{group}_IDS(ALIAS)" for group in groups)
result = subprocess.run(shlex.split(os.environ.get("CC", "cc")) +
                        ["-E", "-P", "-x", "c", "-"], input=source,
                        text=True, capture_output=True, check=True)
ids = sorted(set(int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", result.stdout)))
if not ids or 0x1916 not in ids:
    sys.exit("Skylake 1916 missing from alias expansion")
print("# SPDX-License-Identifier: MIT")
print("# Generated by drivers/i915/gen-aliases.py from drivers/i915/PIN.")
print("# PCH Gen6-Gen9.5 only; never install as IPS driver-action aliases.")
print("# drmadm select new binds these; legacy removes new-only bindings.")
for device in ids:
    print(f"pci8086,{device:x}")
