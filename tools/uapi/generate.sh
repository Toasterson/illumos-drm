# Regenerates the DRM userland interface of the drm-uapi crate:
#
#   crates/drm-uapi/src/bindings.rs  structures and constants (bindgen)
#   crates/drm-uapi/src/ioctl.rs     DRM_IOCTL_* numbers (gen_uapi.py)
#   tools/uapi/drm_layout.c          C half of the layout check (gen_uapi.py)
#   xtask/src/uapi_table.rs          Rust half of the layout check (gen_uapi.py)
#
# The input is the libdrm 2.4.109 release that gfx-drm builds
# (usr/src/common/libdrm/Makefile, same URL and SHA-256) with gfx-drm's
# illumos patch to include/drm/drm.h (tools/uapi/patches, copied from
# gfx-drm d109414c4f). That patched drm.h is what the installed libdrm.so
# was compiled against, so it is the userland ABI the kernel must match.
#
# Needs: curl, xz, patch, python3, bindgen (cargo install bindgen-cli, with
# LIBCLANG_PATH pointing at a libclang), rustfmt, and an illumos-gate
# checkout for the system headers:
#
#   ILLUMOS_GATE=~/illumos-gate tools/uapi/generate.sh
#
# The layout check itself runs on illumos; see the README.
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
GATE=${ILLUMOS_GATE:?set ILLUMOS_GATE to an illumos-gate checkout}
WORK=${WORK:-$ROOT/target/uapi}
BINDGEN=${BINDGEN:-bindgen}
LIBDRM=libdrm-2.4.109
SHA256=629352e08c1fe84862ca046598d8a08ce14d26ab25ee1f4704f993d074cb7f26
URL=https://dri.freedesktop.org/libdrm/$LIBDRM.tar.xz

mkdir -p "$WORK"
if [ ! -f "$WORK/$LIBDRM.tar.xz" ]; then
	curl -sSfL -o "$WORK/$LIBDRM.tar.xz" "$URL"
fi
if command -v sha256sum >/dev/null 2>&1; then
	echo "$SHA256  $WORK/$LIBDRM.tar.xz" | sha256sum -c -
else
	echo "$SHA256  $WORK/$LIBDRM.tar.xz" | shasum -a 256 -c -
fi
rm -rf "${WORK:?}/$LIBDRM"
(cd "$WORK" && xz -dc "$LIBDRM.tar.xz" | tar -xf - &&
    patch -p0 < "$ROOT/tools/uapi/patches/incl-drm-drm-h.patch")
INC=$WORK/$LIBDRM/include/drm

"$BINDGEN" "$ROOT/tools/uapi/wrapper.h" -o "$ROOT/crates/drm-uapi/src/bindings.rs" \
    --use-core --ctypes-prefix core::ffi \
    --allowlist-type '_?drm_.*' --allowlist-var 'DRM_.*|VIRTGPU_.*' \
    --no-prepend-enum-name --default-enum-style consts \
    --with-derive-default \
    --raw-line "// Generated by tools/uapi/generate.sh from $LIBDRM with the illumos patch in tools/uapi/patches." \
    --raw-line "// Target: x86_64-pc-solaris2.11, system headers from illumos-gate $(git -C "$GATE" rev-parse --short=10 HEAD)." \
    --raw-line "// Do not edit; rerun the generator." \
    -- --target=x86_64-pc-solaris2.11 -nostdinc -I"$INC" \
    -isystem "$GATE/usr/src/head" -isystem "$GATE/usr/src/uts/common" -isystem "$GATE/usr/src/uts/intel"

python3 "$ROOT/tools/uapi/gen_uapi.py" "$INC" "$ROOT/crates/drm-uapi/src/bindings.rs" "$ROOT"

rustfmt --edition 2024 --config-path "$ROOT/rustfmt.toml" \
    "$ROOT/crates/drm-uapi/src/bindings.rs" "$ROOT/crates/drm-uapi/src/ioctl.rs" "$ROOT/xtask/src/uapi_table.rs"
echo "headers used: $INC"
